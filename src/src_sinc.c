/*
**	The coefficient tables are generated by Octave/make_sinc_table.m, which
**	also describes their layout. Each header holds the filter, sampled at
**	resolution points per input sample, in two forms :
**
**	- The cubic table used when downsampling. For each interval between two
**	  points it holds the four coefficients of the polynomial which gives the
**	  filter values in that interval.
**
**	- The polyphase table of resolution + 4 rows of poly_row_len entries used
**	  when not downsampling. Row r holds the filter values (r - 1) / resolution
**	  + j input samples from the centre for j = 0, 1, 2 ...
**
**	Either way the filter is evaluated between the points using 4 point (cubic)
**	Lagrange interpolation. That needs far fewer points than the linear
**	interpolation used up to version 0.2.2, so the tables are small enough to
**	stay in the CPU cache even for the best quality converter.
*/

/*
**	The tables are aligned so that the four polynomial coefficients for an
**	interval and four consecutive entries of a row of the polyphase table are
**	always in the same cache line.
*/
#if defined (__GNUC__) || defined (__clang__)
#	define SINC_TABLE_ALIGN(bytes)	__attribute__ ((aligned (bytes)))
#elif defined (_MSC_VER)
#	define SINC_TABLE_ALIGN(bytes)	__declspec (align (bytes))
#else
#	define SINC_TABLE_ALIGN(bytes)
#endif

